// tests/attribution.test.js — R-01 (2026-08-24, pc-red-team, BLOCKER): the
// footer legend rendered "GENERATED — Written by gemini-3.6-flash. Prose
// only." and three Ledger chips were tagged GENERATED, while
// data/explanations.js was an empty placeholder and no model was ever
// called in this build. A curl of the public deployment disproved the
// legend in one command. This file pins the fix by scanning source, the
// same technique tests/purity.test.js already uses for the core/ boundary:
// it fails the build if a false model-authorship claim ever comes back,
// anywhere it could actually be shipped and read by a judge or a browser.

import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import explanations from "../data/explanations.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");

// Every directory Vercel actually serves (per .vercelignore) plus the two
// root files a browser loads directly. .crew/, tools/ and tests/ are
// excluded here on purpose: tests/ is this file's own home (mentioning
// "gemini" while explaining the regression is not a shipped claim), and
// .crew/tools disclosure/staleness is R-05's concern, already fixed and
// re-verified separately (curl returns 404 live).
const SHIPPED_DIRS = ["ui", "data"];
const SHIPPED_ROOT_FILES = ["index.html", "app.js", "styles.css"];

function jsAndHtmlFilesIn(dir) {
  return readdirSync(dir)
    .filter((name) => name.endsWith(".js") || name.endsWith(".html") || name.endsWith(".css"))
    .map((name) => join(dir, name));
}

function allShippedFiles() {
  const files = SHIPPED_ROOT_FILES.map((name) => join(ROOT, name));
  for (const dir of SHIPPED_DIRS) {
    files.push(...jsAndHtmlFilesIn(join(ROOT, dir)));
  }
  return files;
}

test("test_no_shipped_file_names_a_specific_model_id", () => {
  // Nobody has verified any model ID against the vendor's current docs
  // (T-16/T-17 never ran) -- a model version visible in the UI that
  // contradicts the vendor's docs is on the hostile-read checklist and has
  // sunk a winner before. No shipped file may name one until a real call
  // with that ID has actually succeeded.
  const geminiRe = /gemini/i;
  for (const path of allShippedFiles()) {
    const source = readFileSync(path, "utf8");
    assert.ok(!geminiRe.test(source), `${path.replace(ROOT + "/", "")} names a model ID ("gemini"), but no model was ever called in this build`);
  }
});

test("test_no_shipped_file_claims_a_model_wrote_something", () => {
  // The exact false phrase that shipped, and the general shape of it: any
  // sentence claiming something on this page was "written by" a model, or
  // "generated by" one, when no model call happened.
  const forbidden = [/written by\s+\S*(gemini|gpt|claude|llama|featherless)/i, /generated by\s+\S*(gemini|gpt|claude|llama|featherless)/i];
  for (const path of allShippedFiles()) {
    const source = readFileSync(path, "utf8");
    for (const re of forbidden) {
      assert.ok(!re.test(source), `${path.replace(ROOT + "/", "")} matches forbidden pattern ${re} (false model-authorship claim)`);
    }
  }
});

test("test_ledger_row_expander_never_tags_prose_as_generated", () => {
  // The per-rule expander used to render a GENERATED chip next to
  // "why a model still reads this" while the prose behind it was empty
  // (data/explanations.js's byRule: {}). The prose is now real, but it is
  // human-written and deterministic, derived from the rule's own Unicode
  // citation -- so it must be tagged RULE, the same tag the citation itself
  // carries, never GENERATED.
  const source = readFileSync(join(ROOT, "ui", "ledger.js"), "utf8");
  assert.ok(!/chip\(\s*"generated"\s*\)/.test(source), 'ui/ledger.js still calls chip("generated")');
});

test("test_explanations_byRule_is_non_empty_and_not_model_output", () => {
  // The placeholder ("PLACEHOLDER. Not yet generated.", byRule: {}) is gone,
  // replaced with real prose -- but that prose must be honestly sourced.
  assert.ok(Object.keys(explanations.byRule).length > 0, "data/explanations.js's byRule is empty");
  assert.equal(explanations.generatedAt, null, "data/explanations.js claims a generation timestamp with no model run behind it");
  assert.ok(!/gemini/i.test(explanations.source || ""), "data/explanations.js's source field names a model");
});
