// ui/legend.js — the footer: the five epistemic tag chips (including the
// unused, struck-through Simulated), the honesty note, and the provenance
// line built from the modules that already carry those numbers.

import { el, clear, chip } from "./dom.js";

const CHIPS = [
  { kind: "observed", desc: "Computed from the text in your textarea, just now, in your browser." },
  { kind: "rule", desc: "Taken from rulepack.v1, a versioned data file with a Unicode citation per rule — includes the per-rule explanation prose, which is human-written, not model output." },
  { kind: "cached", desc: "Computed earlier, off this machine, and committed to the repo." },
  { kind: "generated", desc: "unused — no model was called in this build. If a model ever writes prose for this page, that content would be tagged GENERATED and nothing else on this page would move; today nothing is." },
  { kind: "simulated", desc: "unused — no value on this page is invented." },
];

/**
 * @param {HTMLElement} container
 * @param {{rulepackVersion:string, corpusSeed:number, testResults:{pass:number,total:number,dependencies:number}}} data
 */
export function renderLegend(container, { rulepackVersion, corpusSeed, testResults }) {
  clear(container);

  container.appendChild(
    el(
      "div",
      { class: "legend-chips" },
      CHIPS.map((c) => el("div", { class: "legend-chip-group" }, [chip(c.kind), el("span", { class: "legend-chip-desc" }, c.desc)]))
    )
  );

  container.appendChild(
    el(
      "p",
      { class: "legend-honesty" },
      "Detection, offsets and sanitization are real, computed by pure functions from the text you paste. The corpus is real and synthetic — generated by us, not a downloaded dataset. The Obedience Table (when present) is real model runs, cached, graded by a deterministic string check, never re-run on your click. Per-rule prose is RULE — deterministic text a human derived from the same Unicode citation printed beside it, not model output; no model was called anywhere in this build. Rendering-layer attacks (HTML comments, white-on-white CSS) are out of scope — this page reads plain text, it does not render one."
    )
  );

  container.appendChild(
    el(
      "p",
      { class: "legend-provenance" },
      `rulepack v${rulepackVersion} · corpus seed ${corpusSeed} · ${testResults.pass}/${testResults.total} tests · ${testResults.dependencies} dependencies · 0 requests to any model, API or third-party host — every file this page loads is same-origin static`
    )
  );
}
